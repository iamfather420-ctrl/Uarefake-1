import { useState, useEffect } from 'react';
import { motion, AnimatePresence } from 'motion/react';
import { Shield, Zap, Target, ArrowRight, Check, Wallet, Cpu, Globe, Link as LinkIcon } from 'lucide-react';
import { cn } from '../lib/utils';
import { useAppKit, useAppKitAccount } from '@reown/appkit/react';

interface OnboardingProps {
  onComplete: (config: { payoutAddress: string; payoutAddressSol: string; strategy: 'PAYOUT' | 'TREASURY_GAS' }) => void;
}

export function Onboarding({ onComplete }: OnboardingProps) {
  const [step, setStep] = useState(1);
  const [payoutAddress, setPayoutAddress] = useState('0x346f86E8e86418C16b51996f82c6Df0D4fcb2E99');
  const [payoutAddressSol, setPayoutAddressSol] = useState('Ai3KhYFk24F54YWb3B94ev3LfF27djJwHzx54eCM8fFT');
  const [strategy, setStrategy] = useState<'PAYOUT' | 'TREASURY_GAS'>('PAYOUT');

  const { open } = useAppKit();
  const { address, isConnected } = useAppKitAccount();

  useEffect(() => {
    if (address) {
      if (address.startsWith('0x')) {
        setPayoutAddress(address);
      } else {
        setPayoutAddressSol(address);
      }
    }
  }, [address]);

  const steps = [
    {
      title: "Identity & Security",
      icon: Shield,
      description: "Welcome to your self sufficient kingdom Anons. The future of government identity systems starts here—10 years ahead of time."
    },
    {
      title: "Universal Basic Income (UBI)",
      icon: Wallet,
      description: "Setup your digital wallet addresses. These are your personal receiving addresses for your autonomous Universal Basic Income (UBI) generated by the system."
    },
    {
      title: "Financial Autonomy",
      icon: Zap,
      description: "Choose how to handle your passive income. Claim it straight to your wallet, or reinvest it to generate even more digital income."
    }
  ];

  const handleNext = () => {
    if (step < steps.length) {
      setStep(step + 1);
    } else {
      onComplete({ payoutAddress, payoutAddressSol, strategy });
    }
  };

  return (
    <div className="fixed inset-0 z-[100] flex items-center justify-center p-4 bg-black/90 backdrop-blur-xl">
      <motion.div 
        initial={{ opacity: 0, scale: 0.9, y: 20 }}
        animate={{ opacity: 1, scale: 1, y: 0 }}
        className="w-full max-w-xl bg-card border border-primary/30 rounded-lg overflow-hidden shadow-[0_0_50px_rgba(57,255,20,0.1)]"
      >
        <div className="h-1 bg-muted">
          <motion.div 
            className="h-full bg-primary"
            initial={{ width: '0%' }}
            animate={{ width: `${(step / steps.length) * 100}%` }}
          />
        </div>

        <div className="p-8">
          <AnimatePresence mode="wait">
            <motion.div
              key={step}
              initial={{ opacity: 0, x: 20 }}
              animate={{ opacity: 1, x: 0 }}
              exit={{ opacity: 0, x: -20 }}
              className="space-y-6"
            >
              <div className="flex items-center gap-4">
                <div className="w-12 h-12 bg-primary/10 rounded-full flex items-center justify-center border border-primary/20">
                  {(() => {
                    const Icon = steps[step - 1].icon;
                    return <Icon className="w-6 h-6 text-primary" />;
                  })()}
                </div>
                <div>
                  <h2 className="text-2xl font-bold uppercase tracking-widest text-primary">{steps[step - 1].title}</h2>
                  <div className="text-[10px] uppercase text-muted-foreground tracking-[2px]">Phase {step} of {steps.length}</div>
                </div>
              </div>

              <p className="text-muted-foreground text-sm leading-relaxed italic">
                "{steps[step - 1].description}"
              </p>

              {step === 2 && (
                <div className="space-y-4 pt-4">
                  <div className="flex justify-center mb-6">
                    <button
                      onClick={() => open()}
                      className="flex items-center gap-2 bg-primary/20 hover:bg-primary/30 border border-primary/50 text-primary px-6 py-3 rounded-md font-bold uppercase tracking-widest text-xs transition-all"
                    >
                      <LinkIcon className="w-4 h-4" />
                      {isConnected ? "Wallet Connected" : "Auto-Connect Wallet"}
                    </button>
                  </div>
                  
                  <div className="relative flex items-center py-2">
                    <div className="flex-grow border-t border-border"></div>
                    <span className="flex-shrink-0 mx-4 text-muted-foreground text-[10px] uppercase tracking-widest">or enter manually</span>
                    <div className="flex-grow border-t border-border"></div>
                  </div>

                  <div className="space-y-2 pt-2">
                    <label className="text-[10px] uppercase tracking-widest text-muted-foreground flex items-center gap-2">
                      <Globe className="w-3 h-3" /> EVM / Multichain Address
                    </label>
                    <input 
                      type="text"
                      className="w-full bg-black/40 border border-border rounded px-3 py-2 font-mono text-xs text-primary focus:border-primary outline-none"
                      value={payoutAddress}
                      onChange={(e) => setPayoutAddress(e.target.value)}
                    />
                  </div>
                  <div className="space-y-2">
                    <label className="text-[10px] uppercase tracking-widest text-muted-foreground flex items-center gap-2">
                      <Target className="w-3 h-3" /> Solana Address
                    </label>
                    <input 
                      type="text"
                      className="w-full bg-black/40 border border-border rounded px-3 py-2 font-mono text-xs text-primary focus:border-primary outline-none"
                      value={payoutAddressSol}
                      onChange={(e) => setPayoutAddressSol(e.target.value)}
                    />
                  </div>
                </div>
              )}

              {step === 3 && (
                <div className="grid grid-cols-1 gap-4 pt-4">
                  <button 
                    onClick={() => setStrategy('PAYOUT')}
                    className={cn(
                      "p-4 border rounded-md text-left transition-all group",
                      strategy === 'PAYOUT' ? "bg-primary/10 border-primary shadow-[0_0_15px_rgba(57,255,20,0.1)]" : "bg-black/20 border-border hover:border-primary/50"
                    )}
                  >
                    <div className="flex justify-between items-start mb-2">
                      <span className={cn("text-xs font-bold uppercase tracking-widest", strategy === 'PAYOUT' ? "text-primary" : "text-muted-foreground")}>Direct Payout</span>
                      {strategy === 'PAYOUT' && <Check className="w-4 h-4 text-primary" />}
                    </div>
                    <p className="text-[11px] text-muted-foreground leading-relaxed">Send my digital UBI income directly to my personal wallets immediately.</p>
                  </button>

                  <button 
                    onClick={() => setStrategy('TREASURY_GAS')}
                    className={cn(
                      "p-4 border rounded-md text-left transition-all group",
                      strategy === 'TREASURY_GAS' ? "bg-amber-500/10 border-amber-500 shadow-[0_0_15px_rgba(245,158,11,0.1)]" : "bg-black/20 border-border hover:border-amber-500/50"
                    )}
                  >
                    <div className="flex justify-between items-start mb-2">
                      <span className={cn("text-xs font-bold uppercase tracking-widest", strategy === 'TREASURY_GAS' ? "text-amber-500" : "text-muted-foreground")}>Reinvest to Grow</span>
                      {strategy === 'TREASURY_GAS' && <Check className="w-4 h-4 text-amber-500" />}
                    </div>
                    <p className="text-[11px] text-muted-foreground leading-relaxed">Reinvest profits back into the UBI Engine to power more automated generation.</p>
                  </button>
                </div>
              )}
            </motion.div>
          </AnimatePresence>

          <div className="mt-12 flex justify-between items-center">
            <div className="flex gap-1">
              {steps.map((_, i) => (
                <div 
                  key={i} 
                  className={cn(
                    "w-2 h-2 rounded-full transition-all duration-300",
                    i + 1 === step ? "w-6 bg-primary" : "bg-muted"
                  )} 
                />
              ))}
            </div>
            <button 
              onClick={handleNext}
              className="flex items-center gap-2 bg-primary text-black px-8 py-3 rounded font-bold uppercase tracking-widest text-xs hover:bg-white transition-colors group"
            >
              {step === steps.length ? "Engage Protocol" : "Next Phase"}
              <ArrowRight className="w-4 h-4 group-hover:translate-x-1 transition-transform" />
            </button>
          </div>
        </div>
        
        <div className="bg-muted/30 p-4 border-t border-border flex items-center justify-between">
          <div className="flex items-center gap-2 text-[10px] text-muted-foreground font-mono">
            <Cpu className="w-3 h-3 text-primary animate-pulse" />
            <span>HEURISTIC ENGINE: ONLINE</span>
          </div>
          <div className="text-[10px] text-muted-foreground font-mono">
            VERSION 1.2.0-SOVEREIGN
          </div>
        </div>
      </motion.div>
    </div>
  );
}
