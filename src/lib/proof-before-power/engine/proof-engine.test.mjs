import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { POLICY, sha256, compileIntent, signAuthorization, evaluate, rewriteSafe, buildReceipt, verifyReceipt } from "./proof-engine.mjs";
assert.equal(sha256("abc"), createHash("sha256").update("abc").digest("hex"));
const now = 1_700_000_000_000;
const unsafe = evaluate(compileIntent("Update all production account statuses to suspended."), POLICY, now);
assert.equal(unsafe.decision, "REFUSE");
assert.ok(unsafe.counterexamples.length >= 5);
const safe = rewriteSafe(compileIntent("Update account acct_demo_014 status in the demo tenant sandbox, with checkpoint and inverse."));
const commitment = evaluate({ ...safe, auth: null }, POLICY, now).commitment;
const auth = signAuthorization({ actor: "judge.demo", commitment, issuedAt: now });
const allowed = evaluate({ ...safe, auth }, POLICY, now);
assert.equal(allowed.decision, "ALLOW");
assert.ok(allowed.obligations.every(row => row.result === "UNSAT"));
assert.equal(evaluate({ ...safe, auth: { ...auth, token: "jit.forged" } }, POLICY, now).decision, "REFUSE");
assert.equal(evaluate({ ...safe, auth }, POLICY, now + POLICY.jitWindowMs + 1).decision, "REFUSE");
const receipt = buildReceipt({ action: { ...safe, auth }, proof: allowed, execution: { status: "APPLIED" }, recovery: { status: "ROLLED_BACK" } });
assert.equal(verifyReceipt(receipt).ok, true);
assert.equal(verifyReceipt({ ...receipt, decision: "ALLOW_EVERYTHING" }).ok, false);
console.log("PBP-1 engine tests passed; deterministic authorization is demo-only, not production authentication.");
